% SX8FW Theoretical Parameters from "Estimation of the Lateral Aerodynamic
% Coefficients for Skywalker X8 Flying Wing from Real Flight-Test Data"
% published in Acta Polytechnica 58(2):77–91, 2018
% https://scispace.com/pdf/estimation-of-the-lateral-aerodynamic-coefficients-for-1mazzoqgqw.pdf

m = 4.5; % Mass (kg)

Jx = 0.45; % Moments of Interia (X) (kg*m^2)
Jy = 0.325; % (Y)
Jz = 0.75; % (Z)
% These moments tell us how much torque is required to angularly accelerate
% the body of the aircraft around one of it's axes. 

Jxz = 0.06; % Product of Intertia (XZ) (kg*m^2)
% This tells us how asymmetric the mass distribution it between two axes.
% Since aircraft are built to be symmetric - that's why Jxy and Jyz are zero.
% With Jxz not equal 0 that means that there is coupling of moments between
% the x and z axes. What this physically means is that when we rotate
% around our x-axis we also get rotation around our z-axis due to how the
% mass is distributed. That means if we roll, we'll also get some yaw. 

S = 0.75; % Wing Area (m^2)
b = 2.21; % Wing Span (m)
c = 0.3571; % Mean Aerodynamic Chord (m)
% Since this is a tapered wing the chord of the wing changes as we go along
% the length of the wing. This is a representative chord length that
% translates that translates that pitching-moment of our tapered wing into
% the pitching-moment of an idealized rectangular wing so the aerodynamic
% equations are easier. 
rho = 1.2682; % Air Density (kg/m^3)

% Laterial-Directional Derivatives 
% Sideslip Derivatives
% Sideslip occurs when a aircraft moves in a direction sideways from it's
% direction of motion as a result of air (e.g. wind) pushing on the
% wings/fuselage.  
CY_beta = -0.1949; % Side Force / Unit Sideslip
% This coefficient tells us how much the aircraft is pushed
% given the force from the air.
Cl_beta = -0.0765; % Rolling Moment / Unit Sideslip
% If sideslip hits us in the roll how does our system respond?
% Negative is stabilizing here since if our left wing is pushed down the
% results is a force that'll bring our left wing back up and restore the
% wings back to their level position. 
Cn_beta = 0.0403; % Yawing Moment / Unit Sideslip
% If the sideslip hits us in yaw how does our system respond?
% Positive is stabilizing here since the response is a moment that pushes 
% us back into the relative wind which is initially sideslip.

% Roll Rate Derivatives
% These tell us our moments given that we are activley rolling. 
Cl_p = -0.4018; % Rolling Moment / Unit Roll Rate
Cn_p = -0.0247; % Yawing Moment / Unit Roll Rate

% Yaw Rate Derivatives
% These tell us our moments given that we are activley yawing. 
Cn_r = -0.1252; % Yawing Moment / Unit Yaw Rate
Cl_r = 0.025; % Rolling Moment / Unit Yaw Rate

% Aileron Deflection
% Our input. In aerodynamics, forces are generated by deflection of a
% control surface and in this case the ailerons wihch are little tabs on
% the end of the wings. 
Cl_deltaA = 0.2987; % Rolling Moment / Unit Aileron Deflection
Cn_deltaA = -0.0076; % Yawing Moment / Unit Aileron Deflection
CY_deltaA = -0.0696; % Side Force / Unit Aileron Deflection